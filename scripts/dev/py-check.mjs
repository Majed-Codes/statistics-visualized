import { chromium, webkit } from '@playwright/test';
const engine = process.argv[2] === 'webkit' ? webkit : chromium;
const browser = await engine.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const t0 = Date.now();
await page.goto('http://localhost:5174/#/lab');
await page.getByTestId('start-python').click();
await page.getByTestId('python-bar').getByText('Python ready').waitFor({ timeout: 120000 });
console.log('ready after', (Date.now() - t0) / 1000, 's', await page.getByTestId('python-status').innerText());
const cell = (id) => page.getByTestId(id);
await cell('run-cell-0').getByTestId('run-cell').click();
await cell('run-cell-0').getByTestId('live-output').waitFor({ timeout: 120000 });
console.log('cell-0 done', (Date.now() - t0) / 1000);
await cell('run-cell-1').getByTestId('run-cell').click();
await cell('run-cell-1').getByTestId('live-output').waitFor({ timeout: 180000 });
console.log('cell-1:', (await cell('run-cell-1').getByTestId('live-output').innerText()).slice(0, 400));
await page.getByTestId('run-corrected').click();
await cell('run-cell-18-fixed').getByTestId('live-output').waitFor({ timeout: 180000 });
console.log('PCA corrected:', (await cell('run-cell-18-fixed').getByTestId('live-output').innerText()).slice(0, 700));
console.log('total', (Date.now() - t0) / 1000, 's', 'errors:', errs);
if (process.argv[3]) await page.screenshot({ path: process.argv[3] });
await browser.close();
